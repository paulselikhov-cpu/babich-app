package com.platform.chat.domain.location.enums;

/**
 * Тип локации — классификация на 3 значения (кто владеет и как локация живёт).
 *
 * Конкретная разновидность локации задаётся полем {@code Location.code}
 * (для системных — одна из констант {@link SystemLocationCode}), а не этим enum.
 *
 * - {@link #SYSTEM} — системная локация района (мэрия, площадь Ленина, банк…),
 *   создаётся автоматически `data.sql` при инициализации района, доступна всем
 *   жителям района без приглашения;
 * - {@link #DEFAULT} — пользовательская локация без выделенной роли
 *   (квартира, обычное место); таких создаётся большинство;
 * - {@link #BUSINESS} — пользовательская бизнес-локация (заведение).
 *   Пока не создаётся игроками, зарезервировано под будущий механизм.
 */
public enum LocationType {
    /** Системная локация района */
    SYSTEM,
    /** Пользовательская локация без выделенной роли. */
    DEFAULT,
    /** Пользовательская бизнес-локация */
    BUSINESS
}
